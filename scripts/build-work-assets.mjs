// Turns the selected captures into responsive AVIF/WebP stills, copies the loops and
// their posters, and writes src/content/media.generated.ts with every size.
// Usage: npm run assets            (all cases)
//        npm run assets -- physiomax   (one case)
import fs from 'node:fs';
import path from 'node:path';
import sharp from 'sharp';
import { ASSETS, CAPTURES } from './work-assets.mjs';
import { buildWallAssets } from './build-wall-assets.mjs';

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1')), '..');
const OUT = path.join(ROOT, 'public', 'work-media');
const GEN = path.join(ROOT, 'src', 'content', 'media.generated.ts');
const only = process.argv[2];

const DESKTOP_W = [960, 1600, 2400];
const PHONE_W = [390, 780, 1170];
const BA_DESKTOP_W = [800, 1600];
const BA_PHONE_W = [390, 780];

const existing = fs.existsSync(GEN) ? JSON.parse((fs.readFileSync(GEN, 'utf8').match(/\/\*DATA(.*)DATA\*\//s) || [, '{}'])[1]) : {};
const data = { stills: existing.stills || {}, ba: existing.ba || {}, loops: existing.loops || {} };

async function encode(input, crop, widths, base) {
  const meta = await sharp(input).metadata();
  const srcW = crop ? crop.width : meta.width;
  const srcH = crop ? crop.height : meta.height;
  const ws = widths.filter((w) => w <= srcW);
  if (!ws.length || ws[ws.length - 1] < Math.min(srcW, widths[widths.length - 1])) ws.push(srcW);
  const uniq = [...new Set(ws)].sort((a, b) => a - b);
  for (const w of uniq) {
    const pipe = () => {
      let p = sharp(input);
      if (crop) p = p.extract(crop);
      return p.resize({ width: w, withoutEnlargement: true });
    };
    await Promise.all([
      pipe().avif({ quality: 56, effort: 4 }).toFile(`${base}-${w}.avif`),
      pipe().webp({ quality: 80, effort: 5 }).toFile(`${base}-${w}.webp`),
    ]);
  }
  return { w: srcW, h: srcH, widths: uniq };
}

for (const [slug, cfg] of Object.entries(ASSETS)) {
  if (only && only !== slug) continue;
  const dir = path.join(OUT, slug);
  fs.mkdirSync(dir, { recursive: true });
  for (const [rel, name, opts = {}] of cfg.stills) {
    const input = path.join(CAPTURES, cfg.dir, rel);
    if (!fs.existsSync(input)) {
      console.log('MISSING', input);
      continue;
    }
    const phone = name.includes('--phone');
    if (opts.only !== 'ba') {
      data.stills[`${slug}/${name}`] = await encode(input, opts.crop, phone ? PHONE_W : DESKTOP_W, path.join(dir, name));
    }
    if (opts.ba) {
      data.ba[`${slug}/${name}`] = await encode(input, opts.crop, phone ? BA_PHONE_W : BA_DESKTOP_W, path.join(dir, `${name}-ba`));
    }
    console.log(slug, name);
  }
  for (const [rel, name] of cfg.loops) {
    const input = path.join(CAPTURES, cfg.dir, rel);
    if (!fs.existsSync(input)) {
      console.log('MISSING', input);
      continue;
    }
    fs.copyFileSync(input, path.join(dir, `${name}.mp4`));
    const poster = input.replace('.mp4', '--poster.jpg');
    const phone = name.includes('--phone');
    const pm = await sharp(poster).metadata();
    const pw = Math.min(pm.width, phone ? 780 : 1600);
    await sharp(poster).resize({ width: pw }).webp({ quality: 80 }).toFile(path.join(dir, `${name}-poster.webp`));
    data.loops[`${slug}/${name}`] = { w: pw, h: Math.round((pm.height * pw) / pm.width), bytes: fs.statSync(input).size };
    console.log(slug, name, 'loop');
  }
}

// The portrait used on the homepage and the about page
if (!only || only === 'site') {
  const src = 'C:/Work/kinetikare-physio-landing-page/public/images/professional-photo-kareem-hassanein-registered-physiotherapist-burlington-waterdown-flamborough-oakville-carlisle.png';
  fs.mkdirSync(path.join(OUT, 'site'), { recursive: true });
  data.stills['site/portrait'] = await encode(src, null, [480, 960, 1440], path.join(OUT, 'site', 'portrait'));
  console.log('site portrait');
}

const sortObj = (o) => Object.fromEntries(Object.entries(o).sort(([a], [b]) => a.localeCompare(b)));
const out = { stills: sortObj(data.stills), ba: sortObj(data.ba), loops: sortObj(data.loops) };
fs.writeFileSync(
  GEN,
  `// Generated by scripts/build-work-assets.mjs. Do not edit by hand.\n/*DATA${JSON.stringify(out)}DATA*/\n` +
    `export type StillInfo = { w: number; h: number; widths: number[] };\n` +
    `export type LoopInfo = { w: number; h: number; bytes: number };\n` +
    `export const STILLS: Record<string, StillInfo> = ${JSON.stringify(out.stills, null, 1)};\n` +
    `export const BA: Record<string, StillInfo> = ${JSON.stringify(out.ba, null, 1)};\n` +
    `export const LOOPS: Record<string, LoopInfo> = ${JSON.stringify(out.loops, null, 1)};\n`
);
console.log('wrote', GEN);
await buildWallAssets(only);
